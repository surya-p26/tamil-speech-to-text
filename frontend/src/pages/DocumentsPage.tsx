import { useEffect, useState } from "react";
import type { Page } from "../types";
import {
  type SavedDocument,
  fetchGeneratedDocuments,
  downloadSavedDocument,
} from "../api";
import { Icon } from "../components/ui/Icons";
import { Button, Card, PageHead } from "../components/ui/UIComponents";
import { formatDocumentSize, formatDocumentDate } from "../utils/formatters";

export function DocumentsPage({ setPage }: { setPage: (page: Page) => void }) {
  const [documents, setDocuments] = useState<SavedDocument[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [search, setSearch] = useState("");
  const [format, setFormat] = useState("All formats");
  const [reloadKey, setReloadKey] = useState(0);
  const [downloading, setDownloading] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    setLoading(true);
    setError(null);
    fetchGeneratedDocuments()
      .then((items) => {
        if (active) setDocuments(items);
      })
      .catch((reason) => {
        if (active)
          setError(
            reason instanceof Error
              ? reason.message
              : "Could not load generated documents.",
          );
      })
      .finally(() => {
        if (active) setLoading(false);
      });
    return () => {
      active = false;
    };
  }, [reloadKey]);

  const query = search.trim().toLocaleLowerCase();
  const filteredDocuments = documents.filter((doc) => {
    const matchesSearch =
      !query ||
      `${doc.title} ${doc.filename} ${doc.source_filename}`
        .toLocaleLowerCase()
        .includes(query);
    const matchesFormat =
      format === "All formats" || doc.format.toUpperCase() === format;
    return matchesSearch && matchesFormat;
  });

  const handleDownload = async (doc: SavedDocument) => {
    setDownloading(doc.filename);
    setError(null);
    try {
      await downloadSavedDocument(doc.filename);
    } catch (reason) {
      setError(
        reason instanceof Error
          ? reason.message
          : `Could not download ${doc.filename}.`,
      );
    } finally {
      setDownloading(null);
    }
  };

  return (
    <>
      <PageHead
        title="Documents"
        description="Browse and download the real PDF and DOCX files generated from your Tamil transcriptions."
        action={
          <Button icon="plus" onClick={() => setPage("upload")}>
            Create document
          </Button>
        }
      />
      <Card className="filter-bar">
        <div className="filter-search">
          <Icon name="search" size={18} />
          <input
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            placeholder="Search title, filename or source audio..."
          />
        </div>
        <select
          value={format}
          onChange={(event) => setFormat(event.target.value)}
          aria-label="Filter by document format"
        >
          <option>All formats</option>
          <option>PDF</option>
          <option>DOCX</option>
        </select>
        <Button
          variant="secondary"
          icon="refresh"
          onClick={() => setReloadKey((key) => key + 1)}
        >
          Refresh
        </Button>
      </Card>

      {error && (
        <div className="inline-message warning" role="alert">
          <Icon name="alert" /> {error}
        </div>
      )}
      <div className="card-head document-list-heading">
        <div>
          <h2>Generated documents</h2>
          <p>
            {loading
              ? "Loading saved files..."
              : `${filteredDocuments.length} ${filteredDocuments.length === 1 ? "document" : "documents"}`}
          </p>
        </div>
      </div>

      {loading ? (
        <Card className="empty-documents">
          <div className="state-loader" />
          <h2>Loading documents</h2>
          <p>Checking the files generated by TamilTranscribe.</p>
        </Card>
      ) : filteredDocuments.length === 0 ? (
        <Card className="empty-documents">
          <div className="state-illustration empty">
            <Icon name="folder" size={30} />
          </div>
          <h2>
            {documents.length === 0
              ? "No generated documents yet"
              : "No matching documents"}
          </h2>
          <p>
            {documents.length === 0
              ? "After you generate a PDF or DOCX, it will appear here for download."
              : "Try a different search term or format filter."}
          </p>
          {documents.length === 0 && (
            <Button icon="plus" onClick={() => setPage("upload")}>
              Start transcription
            </Button>
          )}
        </Card>
      ) : (
        <div className="document-grid">
          {filteredDocuments.map((doc) => (
            <Card className="doc-card saved-doc-card" key={doc.filename}>
              <div
                className={`doc-type ${doc.format.toUpperCase() === "DOCX" ? "word" : ""}`}
              >
                {doc.format.toUpperCase()}
              </div>
              <h3 lang="ta" title={doc.title}>
                {doc.title || doc.filename}
              </h3>
              <p>
                {doc.format.toUpperCase()} ·{" "}
                {formatDocumentSize(doc.size_bytes)}
              </p>
              {doc.source_filename && (
                <p className="saved-doc-source" title={doc.source_filename}>
                  Audio: {doc.source_filename}
                </p>
              )}
              <div className="saved-doc-footer">
                <span>{formatDocumentDate(doc.created_at)}</span>
                <button
                  className="icon-btn"
                  disabled={downloading === doc.filename}
                  title={`Download ${doc.format}`}
                  aria-label={`Download ${doc.filename}`}
                  onClick={() => void handleDownload(doc)}
                >
                  <Icon name="download" size={17} />
                </button>
              </div>
            </Card>
          ))}
        </div>
      )}
    </>
  );
}
